// ============================================================
// 交通量カウント
// HTML + CSS + JavaScriptのみで動作
// ============================================================


// ============================================================
// localStorageの保存キー
// ============================================================

const STORAGE_KEY = "traffic_counts";


// ============================================================
// カウントデータ
// ============================================================

const counts = {

    up: {

        car: 0,

        truck: 0,

        bus: 0,

        bike: 0,

        person: 0,

        bicycle: 0

    },

    down: {

        car: 0,

        truck: 0,

        bus: 0,

        bike: 0,

        person: 0,

        bicycle: 0

    }

};


// ============================================================
// 種類
// ============================================================

const types = [

    "car",

    "truck",

    "bus",

    "bike",

    "person",

    "bicycle"

];


// ============================================================
// 方向
// ============================================================

const directions = [

    "up",

    "down"

];


// ============================================================
// キーボード設定
// ============================================================

const KEY_MAP = {

    // -------------------------
    // 上り
    // -------------------------

    "1": [
        "up",
        "car"
    ],

    "2": [
        "up",
        "truck"
    ],

    "3": [
        "up",
        "bus"
    ],

    "4": [
        "up",
        "bike"
    ],

    "5": [
        "up",
        "person"
    ],

    "6": [
        "up",
        "bicycle"
    ],


    // -------------------------
    // 下り
    // -------------------------

    "q": [
        "down",
        "car"
    ],

    "w": [
        "down",
        "truck"
    ],

    "e": [
        "down",
        "bus"
    ],

    "r": [
        "down",
        "bike"
    ],

    "t": [
        "down",
        "person"
    ],

    "y": [
        "down",
        "bicycle"
    ]

};


// ============================================================
// データ保存
// ============================================================

function saveCounts() {

    try {

        localStorage.setItem(

            STORAGE_KEY,

            JSON.stringify(counts)

        );

    } catch (error) {

        console.error(
            "データ保存エラー:",
            error
        );

    }

}


// ============================================================
// データ読み込み
// ============================================================

function loadCounts() {

    try {

        const savedData =
            localStorage.getItem(
                STORAGE_KEY
            );


        // 保存データがない場合

        if (!savedData) {

            return;

        }


        const data =
            JSON.parse(
                savedData
            );


        // -------------------------
        // 上り・下り
        // -------------------------

        directions.forEach(
            direction => {

                if (
                    !data[direction]
                    ||
                    typeof data[direction] !== "object"
                ) {

                    return;

                }


                // -------------------------
                // 車種
                // -------------------------

                types.forEach(
                    type => {

                        const value =
                            data[
                                direction
                            ][type];


                        if (
                            typeof value === "number"
                            &&
                            Number.isInteger(value)
                            &&
                            value >= 0
                        ) {

                            counts[
                                direction
                            ][type] = value;

                        }

                    }
                );

            }
        );


        console.log(
            "保存データを読み込みました。"
        );


    } catch (error) {

        console.error(
            "データ読み込みエラー:",
            error
        );

    }

}


// ============================================================
// 画面のカウント表示を更新
// ============================================================

function updateDisplay(
    direction,
    type
) {

    const element =
        document.getElementById(
            `${direction}-${type}`
        );


    if (!element) {

        return;

    }


    element.textContent =
        counts[
            direction
        ][type];

}


// ============================================================
// 合計を更新
// ============================================================

function updateTotal(
    direction
) {

    const data =
        counts[direction];


    const total =

        data.car +

        data.truck +

        data.bus +

        data.bike +

        data.person +

        data.bicycle;


    const element =
        document.getElementById(
            `${direction}-total`
        );


    if (!element) {

        return;

    }


    element.textContent =
        total;

}


// ============================================================
// 全ての表示を更新
// ============================================================

function updateAllDisplay() {

    directions.forEach(
        direction => {

            types.forEach(
                type => {

                    updateDisplay(
                        direction,
                        type
                    );

                }
            );


            updateTotal(
                direction
            );

        }
    );

}


// ============================================================
// カウント変更
// ============================================================

function changeCount(
    direction,
    type,
    amount
) {

    // -------------------------
    // 不正な方向を防止
    // -------------------------

    if (
        !counts[direction]
    ) {

        return;

    }


    // -------------------------
    // 不正な種類を防止
    // -------------------------

    if (
        typeof counts[
            direction
        ][type] !== "number"
    ) {

        return;

    }


    // -------------------------
    // カウント変更
    // -------------------------

    counts[
        direction
    ][type] += amount;


    // -------------------------
    // 0未満にならないようにする
    // -------------------------

    if (
        counts[
            direction
        ][type] < 0
    ) {

        counts[
            direction
        ][type] = 0;

    }


    // -------------------------
    // 画面更新
    // -------------------------

    updateDisplay(
        direction,
        type
    );


    updateTotal(
        direction
    );


    // -------------------------
    // 保存
    // -------------------------

    saveCounts();

}


// ============================================================
// 全てリセット
// ============================================================

function resetAll() {

    const result =
        window.confirm(
            "全てのカウントをリセットしますか？"
        );


    if (!result) {

        return;

    }


    // -------------------------
    // 全カウントを0にする
    // -------------------------

    directions.forEach(
        direction => {

            types.forEach(
                type => {

                    counts[
                        direction
                    ][type] = 0;

                }
            );

        }
    );


    // -------------------------
    // 画面更新
    // -------------------------

    updateAllDisplay();


    // -------------------------
    // 保存
    // -------------------------

    saveCounts();


    console.log(
        "全てのカウントをリセットしました。"
    );

}


// ============================================================
// キーボード入力
// ============================================================
// 重要：
// event.repeat が true の場合は無視する。
// これによってキーを長押ししても1回しか増えない。
// ============================================================

document.addEventListener(
    "keydown",
    function(event) {

        // -------------------------
        // 入力欄では反応させない
        // -------------------------

        if (

            event.target.tagName === "INPUT"

            ||

            event.target.tagName === "TEXTAREA"

            ||

            event.target.isContentEditable

        ) {

            return;

        }


        // -------------------------
        // 長押しによる連続入力を防止
        // -------------------------
        //
        // キーを押しっぱなしにすると
        // ブラウザはkeydownを繰り返し発生させる。
        //
        // event.repeat が true の場合、
        // 2回目以降のkeydownなので無視する。
        //
        // -------------------------

        if (
            event.repeat
        ) {

            return;

        }


        // -------------------------
        // キーを小文字にする
        // -------------------------

        const key =
            event.key.toLowerCase();


        // -------------------------
        // 対応していないキー
        // -------------------------

        if (
            !KEY_MAP[key]
        ) {

            return;

        }


        // -------------------------
        // ブラウザの標準動作を防止
        // -------------------------

        event.preventDefault();


        // -------------------------
        // 対応する方向・車種を取得
        // -------------------------

        const [
            direction,
            type
        ] = KEY_MAP[key];


        // -------------------------
        // 1回だけ +1
        // -------------------------

        changeCount(
            direction,
            type,
            1
        );

    }
);


// ============================================================
// ページ起動時
// ============================================================

function initialize() {

    // -------------------------
    // 保存データを読み込む
    // -------------------------

    loadCounts();


    // -------------------------
    // 画面を更新
    // -------------------------

    updateAllDisplay();


    // -------------------------
    // コンソール表示
    // -------------------------

    console.log(
        "================================"
    );

    console.log(
        "交通量カウントシステム起動"
    );

    console.log(
        "================================"
    );

    console.log(
        "キーボード操作：ON"
    );

    console.log(
        "長押し防止：ON"
    );

    console.log(
        "上り：1 2 3 4 5 6"
    );

    console.log(
        "下り：Q W E R T Y"
    );

}


// ============================================================
// 起動
// ============================================================

initialize();
